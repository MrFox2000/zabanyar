/**
 * Downloads a flat cartoon illustration for every word in the whole course — and
 * for the reserve word bank that future levels (A2…C1) will draw from — using
 * OpenMoji (CC BY-SA 4.0, see public/words/ATTRIBUTION.md).
 *
 * Level-agnostic: it walks every `src/content/<level>/unit-*.json`, so adding A2
 * and re-running the script is all a new level ever needs.
 *
 *   node scripts/fetch-word-images.mjs
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import wordBank from "./curriculum/word-bank.mjs";

const ROOT = "D:/Projects/zabanyar";
const OUT_DIR = join(ROOT, "public/words");
const BASE = "https://raw.githubusercontent.com/hfg-gmuend/openmoji/master/color/svg";

mkdirSync(OUT_DIR, { recursive: true });

const entries = new Map();
const levels = readdirSync(join(ROOT, "src/content"), { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name);

for (const level of levels) {
  const dir = join(ROOT, "src/content", level);
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".json")).sort()) {
    const unit = JSON.parse(readFileSync(join(dir, file), "utf8"));
    for (const lesson of unit.lessons) {
      const items = [
        ...(lesson.vocab ?? []),
        ...(lesson.teach ?? [])
          .filter((step) => step.kind === "letter")
          .map((step) => ({ en: step.word, emoji: step.emoji })),
      ];
      for (const item of items) {
        if (item.en && item.emoji && !entries.has(item.en)) entries.set(item.en, item.emoji);
      }
    }
  }
}

for (const [en, , emoji] of wordBank) {
  if (en && emoji && !entries.has(en)) entries.set(en, emoji);
}

const slug = (word) =>
  word
    .toLowerCase()
    .replace(/['’.]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const hexCodes = (emoji) => {
  const points = [...emoji].map((character) => character.codePointAt(0).toString(16).toUpperCase());
  const clean = points.filter((point) => point !== "FE0F");
  // keycap emoji (1️⃣) also exist as their digit alone
  const digit = /^\d$/.test(emoji[0] ?? "")
    ? [emoji[0].codePointAt(0).toString(16).toUpperCase().padStart(4, "0")]
    : [];
  return [...new Set([clean.join("-"), points.join("-"), clean[0], ...digit])];
};

async function grab(emoji) {
  for (const code of hexCodes(emoji)) {
    try {
      const response = await fetch(`${BASE}/${code}.svg`);
      if (!response.ok) continue;
      const svg = await response.text();
      if (!svg.includes("<svg")) continue;
      return svg;
    } catch {
      /* try the next code */
    }
  }
  return null;
}

const map = {};
const failures = [];
let done = 0;

for (const [word, emoji] of entries) {
  const file = `${slug(word)}.svg`;
  const target = join(OUT_DIR, file);
  if (existsSync(target)) {
    map[word] = `/words/${file}`;
    done += 1;
    continue;
  }
  const svg = await grab(emoji);
  if (!svg) {
    failures.push(`${word} (${emoji})`);
    continue;
  }
  writeFileSync(target, svg, "utf8");
  map[word] = `/words/${file}`;
  done += 1;
  process.stdout.write(".");
}

const header = [
  "/** generated by scripts/fetch-word-images.mjs — do not edit by hand */",
  "export const WORD_IMAGES: Record<string, string> = " + JSON.stringify(map, null, 2) + ";",
  "",
  "/** the picture for a word, or null when we do not have one */",
  "export function wordImage(word?: string | null): string | null {",
  "  if (!word) return null;",
  "  return WORD_IMAGES[word] ?? null;",
  "}",
  "",
];
writeFileSync(join(ROOT, "src/lib/word-images.ts"), header.join("\n"), "utf8");

console.log(`\n\nlevels: ${levels.join(", ")}`);
console.log(`words: ${entries.size} — downloaded ${done}, missing ${failures.length}`);
if (failures.length) console.log(failures.join(", "));
